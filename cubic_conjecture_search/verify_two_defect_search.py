"""Independent structural and brute-force checks for the round-five search.

Uses only the Python standard library and an already compiled count_descent
executable. The stored graph6 files were independently generated by nauty
geng; their completeness relies on that generator.
"""
import argparse
import importlib.util
import json
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location(
    'templates', ROOT / 'exploratory/two_defect_templates.py')
templates = importlib.util.module_from_spec(spec)
spec.loader.exec_module(templates)


def decode(code):
    n = ord(code[0]) - 63
    assert 0 < n < 63
    adj = [set() for _ in range(n)]
    bit = 0
    for v in range(1, n):
        for u in range(v):
            if (ord(code[1 + bit // 6]) - 63) & (1 << (5 - bit % 6)):
                adj[u].add(v)
                adj[v].add(u)
            bit += 1
    return adj


def components(adj):
    remaining = set(range(len(adj)))
    while remaining:
        start = min(remaining)
        seen = {start}
        queue = [start]
        for v in queue:
            for u in adj[v] - seen:
                seen.add(u)
                queue.append(u)
        remaining -= seen
        yield seen


def signature(adj):
    """Suppress degree-two chains using an edge walk, independent of builder."""
    branches = {v for v, nb in enumerate(adj) if len(nb) == 3}
    assert len(branches) == 2 and all(len(nb) in (2, 3) for nb in adj)
    cs = list(components(adj))
    core = next(c for c in cs if c & branches)
    assert branches <= core
    cycles = tuple(sorted(len(c) for c in cs if c != core))
    used = set()
    chains = []
    for a in sorted(branches):
        for b in sorted(adj[a]):
            if frozenset((a, b)) in used:
                continue
            prev, now, length = a, b, 1
            used.add(frozenset((prev, now)))
            while now not in branches:
                nxt, = adj[now] - {prev}
                prev, now = now, nxt
                length += 1
                used.add(frozenset((prev, now)))
            chains.append((a, now, length))
    assert len(chains) == 3
    loops = sorted(length for a, b, length in chains if a == b)
    links = sorted(length for a, b, length in chains if a != b)
    if not loops:
        assert len(links) == 3 and all(x % 2 for x in links)
        return 0, tuple(links), cycles
    assert len(loops) == 2 and len(links) == 1
    assert all(x >= 4 and x % 2 == 0 for x in loops) and links[0] % 2
    return 1, (*loops, links[0]), cycles


def brute_force(code):
    adj = decode(code)
    masks = [sum(1 << u for u in nb) for nb in adj]
    n = len(adj)
    count, maximum = 0, 0
    for selected in range(1 << n):
        size = selected.bit_count()
        if size < (n + 1) // 2:
            continue
        if all((selected & masks[v]).bit_count() == 2
               for v in range(n) if selected >> v & 1):
            count += 1
            maximum = max(maximum, size)
    return count, maximum


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--counter', type=Path, required=True)
    args = parser.parse_args()
    data = ROOT / 'round5_data'
    complement_codes = (data / 'complements14.g6').read_text().splitlines()
    observed = {signature(decode(code)) for code in complement_codes}
    theoretical = {(kind, core, tc) for sc, kind, core, tc in templates.templates(26)}
    assert observed == theoretical and len(observed) == len(complement_codes) == 22
    cycle_codes = (data / 'cycle_factors12.g6').read_text().splitlines()
    observed_cycles = set()
    for code in cycle_codes:
        adj = decode(code)
        assert all(len(nb) == 2 for nb in adj)
        observed_cycles.add(tuple(sorted(map(len, components(adj)))))
    assert observed_cycles == set(templates.partitions(12)) and len(cycle_codes) == 4

    certificates = json.loads((ROOT / 'certificates.json').read_text())
    codes = [row['graph6'] for row in certificates['graphs'] if ord(row['graph6'][0]) - 63 <= 12]
    assert len(codes) == 112
    with tempfile.TemporaryDirectory() as directory:
        inputs = Path(directory) / 'graphs.g6'
        inputs.write_text('\n'.join(codes) + '\n')
        result = subprocess.run([str(args.counter.resolve()), 'count', str(inputs)],
                                text=True, capture_output=True, check=True)
    rows = result.stdout.splitlines()
    assert len(rows) == len(codes)
    for code, line in zip(codes, rows):
        reported_code, count, maximum, aborted, nodes = line.split()
        assert reported_code == code and aborted == '0'
        assert (int(count), int(maximum)) == brute_force(code)

    summary = []
    for order in (10, 14, 18, 22, 26):
        definitions = list(templates.templates(order))
        expected = json.loads((data / f'two_defect{order}.json').read_text())
        results = [json.loads(line) for line in
                   (data / f'two_defect{order}_results.jsonl').read_text().splitlines()]
        assert len(definitions) == len(expected) == len(results)
        for i, ((sc, kind, core, tc), record, result) in enumerate(zip(definitions, expected, results)):
            assert tuple(record['S_cycles']) == sc and tuple(record['core_lengths']) == core
            assert tuple(record['T_cycles']) == tc
            assert record['core'] == ('theta' if kind == 0 else 'barbell')
            assert result['template_id'] == i and result['order'] == order
            assert result['cases'] == record['expected_cases']
        summary.append(dict(order=order, templates=len(results),
                            completions=sum(row['cases'] for row in results)))
    print(json.dumps(dict(independent_complements=22, independent_cycle_factors=4,
                         exact_counter_crosschecks=112, completed_searches=summary,
                         general_conjecture_solved=False), indent=2))


if __name__ == '__main__':
    main()
